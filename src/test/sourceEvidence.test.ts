import { describe, it } from 'node:test';
import assert from 'node:assert';
import {
  extractBrandName,
  extractBrandInitials,
  createSourceItemFromNormalized,
  getRetrievalStatusBadge,
} from '../services/synthesis/sourceFormatter';
import { NormalizedSearchResult } from '../services/search/types';

describe('Source Evidence & Provenance Derivation', () => {
  it('should accurately extract brand names from domains including multi-part TLDs', () => {
    assert.strictEqual(extractBrandName('bbc.co.uk'), 'Bbc');
    assert.strictEqual(extractBrandName('www.nature.com'), 'Nature');
    assert.strictEqual(extractBrandName('en.wikipedia.org'), 'Wikipedia');
    assert.strictEqual(extractBrandName('blog.cloudflare.com'), 'Cloudflare');
    assert.strictEqual(extractBrandName('who.int'), 'Who');
    assert.strictEqual(extractBrandName('data.gov.au'), 'Data');
  });

  it('should generate sensible initials from brand names', () => {
    assert.strictEqual(extractBrandInitials('Bbc'), 'BBC');
    assert.strictEqual(extractBrandInitials('World Health Organization'), 'WH');
    assert.strictEqual(extractBrandInitials('Nature'), 'NAT');
  });

  it('should preserve actual citation counts from synthesis without overriding to 1', () => {
    const rawResult: NormalizedSearchResult = {
      id: 3,
      title: 'Global Economic Outlook',
      url: 'https://imf.org/outlook',
      domain: 'imf.org',
      snippet: 'Growth projected at 3.2% across advanced economies.',
      rank: 3,
      retrievalStatus: 'retrieved',
      citationsCount: 4, // 4 citations generated by model
    };

    const item = createSourceItemFromNormalized(rawResult);
    assert.strictEqual(item.citationsCount, 4);
    assert.strictEqual(item.id, 3);
    assert.strictEqual(item.domain, 'imf.org');
    assert.strictEqual(item.name, 'Imf');
    assert.strictEqual(item.verified, true);
  });

  it('should default citation count to 0 when query was search-only without synthesis', () => {
    const rawResult: NormalizedSearchResult = {
      id: 1,
      title: 'Solar Panel Efficiency Benchmarks',
      url: 'https://energy.gov/solar',
      domain: 'energy.gov',
      snippet: 'Commercial silicon cell efficiency reached 24.5%.',
      rank: 1,
      retrievalStatus: 'pending',
    };

    const item = createSourceItemFromNormalized(rawResult);
    assert.strictEqual(item.citationsCount, 0);
    assert.strictEqual(item.verified, false);
    assert.strictEqual(item.retrievalStatus, 'pending');
  });

  it('should derive excerpts strictly from retrieved content or snippet without fabricated quotations', () => {
    const resultWithContent: NormalizedSearchResult = {
      id: 1,
      title: 'Test Article',
      url: 'https://example.com/article',
      domain: 'example.com',
      snippet: 'Short search snippet.',
      extractedContent: 'Deep article text extracted by source retriever.',
      rank: 1,
      retrievalStatus: 'retrieved',
    };

    const item1 = createSourceItemFromNormalized(resultWithContent);
    assert.strictEqual(item1.excerpt, 'Deep article text extracted by source retriever.');

    const resultSnippetOnly: NormalizedSearchResult = {
      id: 2,
      title: 'Snippet Only Article',
      url: 'https://example.com/snippet',
      domain: 'example.com',
      snippet: 'Search snippet text.',
      rank: 2,
      retrievalStatus: 'pending',
    };

    const item2 = createSourceItemFromNormalized(resultSnippetOnly);
    assert.strictEqual(item2.excerpt, 'Search snippet text.');

    const resultEmpty: NormalizedSearchResult = {
      id: 3,
      title: 'Empty Article',
      url: 'https://example.com/empty',
      domain: 'example.com',
      snippet: '',
      rank: 3,
      retrievalStatus: 'failed',
    };

    const item3 = createSourceItemFromNormalized(resultEmpty);
    assert.strictEqual(item3.excerpt, 'No text excerpt available from this source.');
  });

  it('should return accurate verification status indicators without claiming independent fact-checking', () => {
    const retrievedBadge = getRetrievalStatusBadge('retrieved', true);
    assert.strictEqual(retrievedBadge.dotClass, 'bg-emerald-500');
    assert.strictEqual(retrievedBadge.label, 'Page Retrieved');

    const blockedBadge = getRetrievalStatusBadge('blocked', false);
    assert.strictEqual(blockedBadge.dotClass, 'bg-amber-500');
    assert.strictEqual(blockedBadge.label, 'Security Blocked');

    const failedBadge = getRetrievalStatusBadge('failed', false);
    assert.strictEqual(failedBadge.dotClass, 'bg-rose-500');
    assert.strictEqual(failedBadge.label, 'Fetch Failed');

    const snippetBadge = getRetrievalStatusBadge('pending', false);
    assert.strictEqual(snippetBadge.dotClass, 'bg-sky-500');
    assert.strictEqual(snippetBadge.label, 'Search Snippet');
  });
});
